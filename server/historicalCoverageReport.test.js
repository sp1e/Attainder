import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { DOSSIER_FILES, packageCoverage } from './historicalCoverage.js';
import { renderStartCoverageReport, sameReport } from './historicalCoverageReport.js';
import { SHIPPED_STATUSES } from './historicalInventory.js';
import { SHIPPED_HISTORICAL_PACKAGES } from './historicalStarts.js';
import { checkStartCoverage } from '../scripts/check-start-coverage.mjs';

const readJson = relative => JSON.parse(readFileSync(new URL(`./seed/historical/${relative}`, import.meta.url), 'utf8'));
const coverages = SHIPPED_HISTORICAL_PACKAGES.map(id => packageCoverage({
  data: readJson(`${id}/scenario.json`).data,
  dossier: DOSSIER_FILES[id] ? readJson(`courts/${DOSSIER_FILES[id]}`) : null,
}));
const rendered = renderStartCoverageReport({ coverages, inventory: null });

// The table rows of the section under `heading`, without the header and separator lines.
const tableRows = (report, heading) => {
  const lines = report.split('\n');
  const start = lines.indexOf(heading);
  assert.ok(start >= 0, `missing ${heading}`);
  const table = [];
  for (const line of lines.slice(start + 1)) {
    if (line.startsWith('#')) break;
    if (line.startsWith('|')) table.push(line);
  }
  return table.slice(2);
};

test('the report lists every start with its counts', () => {
  const lines = rendered.split('\n');
  assert.equal(lines[0], '# Coverage per start');
  assert.equal(lines[1], 'Generated by scripts/check-start-coverage.mjs. Do not edit by hand.');
  const summary = tableRows(rendered, '## Summary');
  assert.equal(summary.length, 4);
  assert.deepEqual(summary.map(row => row.split('|')[1].trim()), SHIPPED_HISTORICAL_PACKAGES);
  assert.deepEqual(summary.map(row => row.split('|')[7].trim()), ['137', '214', '289', '280']);
  assert.match(rendered, /Västra Xia/);
  assert.match(rendered, /Chimú/);
  assert.ok(rendered.includes('The public inventory derivative `server/seed/historical/coverage/inventory.json` is not published yet. The request to Codex is in `docs/development/CODEX-HANDOVER.md`.'));
  assert.ok(rendered.endsWith('\n') && !rendered.includes('\r'));
});

test('the report renders the inventory tables', () => {
  const counts = Object.fromEntries(SHIPPED_STATUSES.map((s, i) => [s, i]));
  const inventory = {
    preparedOn: '2026-11-09', rowCount: 21, withheldRowCount: 400,
    byStart: [...SHIPPED_HISTORICAL_PACKAGES, 'no start'].map(key => ({ key, counts })),
    byRegion: [{ key: 'europe', counts }, { key: 'americas', counts }],
  };
  const report = renderStartCoverageReport({ coverages, inventory });
  assert.match(report, /2026-11-09/);
  assert.match(report, /\b21 rows\b/);
  assert.match(report, /\b400 further rows\b/);
  for (const status of SHIPPED_STATUSES) assert.match(report, new RegExp(`\\| ${status} \\|`));
  assert.match(report, /^\| no start \|/m);
  assert.match(report, /^\| europe \|/m);
  assert.doesNotMatch(report, /is not published yet/);
});

test('the report is stable', () => {
  assert.equal(renderStartCoverageReport({ coverages, inventory: null }), rendered);
});

test('a CRLF copy of the report still matches', () => {
  assert.equal(sameReport(rendered.replace(/\n/g, '\r\n'), rendered), true);
  assert.equal(sameReport(rendered.replace('Chimú', 'Chimu'), rendered), false);
});

test('the committed start coverage report matches the packages', async () => {
  assert.deepEqual(await checkStartCoverage({ check: true }), { starts: 4, inventoryRows: null });
});
