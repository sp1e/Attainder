// Renders docs/coverage/start-coverage.md from the package coverage of each shipped start and,
// once Codex publishes it, the shipped-status tables of the public inventory. Pure functions;
// scripts/check-start-coverage.mjs reads the files and writes or compares the report.
import { SHIPPED_STATUSES } from "./historicalInventory.js";

const INVENTORY_FILE = "server/seed/historical/coverage/inventory.json";
const lf = (text) => text.replace(/\r\n/g, "\n");
const byId = (a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
const plural = (count, word) => `${count} ${word}${count === 1 ? "" : "s"}`;

// A pipe-table cell: one line, pipes escaped, a missing value spelled out.
const cell = (value) => (value === null || value === undefined ? "none" : String(value)).replace(/\r?\n/g, " ").replace(/\|/g, "\\|");
const row = (values) => `| ${values.map(cell).join(" | ")} |`;
const table = (headers, align, rows) => [row(headers), `| ${align.map(a => (a === "r" ? "---:" : "---")).join(" | ")} |`, ...rows.map(row)];
const countTable = (label, counts) => table([label, "Features"], ["l", "r"], Object.entries(counts));

const summary = (coverages) => table(
  ["Start", "Date", "Content version", "Playable", "Map-only", "Review features", "Withheld control", "Sources"],
  ["l", "l", "l", "r", "r", "r", "r", "r"],
  coverages.map(c => [c.contentId, c.date, c.contentVersion, c.playable.length, c.mapOnly.length, c.features.total, c.features.byBoundary["withheld-control"] ?? 0, c.sourceCount]),
);

const playableTable = (playable) => table(
  ["Id", "Swedish name", "Kind", "Region", "Seat", "Sources"], ["l", "l", "l", "l", "l", "r"],
  [...playable].sort(byId).map(p => [p.id, p.nameSv, p.kind, p.regionId, p.seatSv, p.sourceCount]),
);

const mapOnlyTable = (mapOnly) => (mapOnly.length === 0 ? ["None."] : table(
  ["Id", "Swedish name", "Kind", "Dossier status", "Blocked reason"], ["l", "l", "l", "l", "l"],
  [...mapOnly].sort(byId).map(p => [p.id, p.nameSv, p.kind, p.dossierStatus, p.blockedReason]),
));

const startSection = (c) => [
  `## ${c.contentId}`, "",
  `- Swedish era label: ${c.eraLabelSv}`, `- Start date: ${c.date}`, `- Content version: ${c.contentVersion}`, "",
  "### Playable polities", "", ...playableTable(c.playable), "",
  "### Map-only polities", "", ...mapOnlyTable(c.mapOnly), "",
  "### Review features by boundary decision", "", ...countTable("Boundary decision", c.features.byBoundary), "",
  "### Review features by classification", "", ...countTable("Classification", c.features.byClassification), "",
  "### Continent areas", "", ...table(["Area", "Status"], ["l", "l"], c.areas.map(a => [a.area, a.status])), "",
];

const statusTable = (label, entries) => table([label, ...SHIPPED_STATUSES], ["l", ...SHIPPED_STATUSES.map(() => "r")], entries.map(e => [e.key, ...SHIPPED_STATUSES.map(s => e.counts[s])]));

const inventorySection = (inventory) => {
  if (inventory === null) {
    return ["## Inventory", "", `The public inventory derivative \`${INVENTORY_FILE}\` is not published yet. The request to Codex is in \`docs/development/CODEX-HANDOVER.md\`.`, ""];
  }
  const withheld = inventory.withheldRowCount === null ? "" : ` Codex withheld ${plural(inventory.withheldRowCount, "further row")}, which the tables leave out.`;
  return [
    "## Inventory", "",
    `The public inventory derivative \`${INVENTORY_FILE}\` was prepared on ${inventory.preparedOn} and lists ${plural(inventory.rowCount, "row")}.${withheld}`, "",
    "### Shipped status by start", "", ...statusTable("Start", inventory.byStart), "",
    "### Shipped status by region", "", ...statusTable("Region", inventory.byRegion), "",
  ];
};

// `coverages` holds packageCoverage results in SHIPPED_HISTORICAL_PACKAGES order; `inventory` is
// null or { preparedOn, rowCount, withheldRowCount, byStart, byRegion }.
export const renderStartCoverageReport = ({ coverages, inventory }) => [
  "# Coverage per start",
  "Generated by scripts/check-start-coverage.mjs. Do not edit by hand.",
  "",
  "Counts only. Each start's numbers come from its built package and court dossier. Polity tables sort by id.",
  "",
  "## Summary", "", ...summary(coverages), "",
  ...coverages.flatMap(startSection),
  ...inventorySection(inventory),
].join("\n");

// A Windows checkout turns the committed LF file into CRLF; that is not drift.
export const sameReport = (committed, rendered) => lf(committed) === rendered;
